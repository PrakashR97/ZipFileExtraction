
CREATE TABLE ZIP_EXTRACTION_LOG
(
    LOG_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    FILE_NAME VARCHAR2(500),
    SOURCE_PATH VARCHAR2(1000),
    FILE_MODIFIED_DATE TIMESTAMP,
    FILE_SIZE NUMBER(19),

    MONTH_FOLDER VARCHAR2(6),
    DESTINATION_PATH VARCHAR2(1000),

    STATUS VARCHAR2(20),

    START_TIME TIMESTAMP DEFAULT SYSTIMESTAMP,
    END_TIME TIMESTAMP,

    ERROR_MESSAGE VARCHAR2(4000),

    CONSTRAINT CHK_ZIP_STATUS
        CHECK (STATUS IN
            ('PROCESSING', 'SUCCESS', 'FAILED'))
);




public void Main()
{
    try
    {
        string zipPath = Dts.Variables["User::ZipFilePath"]
                            .Value.ToString();

        string destinationRoot =
            Dts.Variables["User::DestinationRoot"]
                .Value.ToString();

        // Read actual Windows Date Modified
        System.IO.FileInfo file =
            new System.IO.FileInfo(zipPath);

        if (!file.Exists)
            throw new System.IO.FileNotFoundException(
                "ZIP file not found", zipPath);

        DateTime modifiedDate = file.LastWriteTime;

        // Store file metadata in SSIS variables
        Dts.Variables["User::ZipFileName"].Value =
            file.Name;

        Dts.Variables["User::ModifiedDate"].Value =
            modifiedDate;

        Dts.Variables["User::FileSize"].Value =
            file.Length;

        // Check current month dynamically
        DateTime today = DateTime.Now;

        if (modifiedDate.Year != today.Year ||
            modifiedDate.Month != today.Month)
        {
            Dts.Events.FireInformation(
                0, "ZIP Extraction",
                "Skipping previous-month file: " + file.Name,
                "", 0, ref fireAgain);

            Dts.TaskResult = (int)ScriptResults.Success;
            return;
        }

        // Generate month folder dynamically
        string monthFolder =
            modifiedDate.ToString("yyyyMM");

        string monthPath =
            System.IO.Path.Combine(
                destinationRoot, monthFolder);

        // Create month folder if it doesn't exist
        System.IO.Directory.CreateDirectory(monthPath);

        // ZIP filename without .zip
        string zipFolderName =
            System.IO.Path.GetFileNameWithoutExtension(
                file.Name);

        string destinationPath =
            System.IO.Path.Combine(
                monthPath, zipFolderName);

        // Store destination details
        Dts.Variables["User::MonthFolder"].Value =
            monthFolder;

        Dts.Variables["User::DestinationPath"].Value =
            destinationPath;

        bool fireAgain = false;

        Dts.Events.FireInformation(
            0, "ZIP Extraction",
            "ZIP: " + file.Name +
            " | Modified: " + modifiedDate +
            " | Destination: " + destinationPath,
            "", 0, ref fireAgain);

        Dts.TaskResult = (int)ScriptResults.Success;
    }
    catch (Exception ex)
    {
        Dts.Events.FireError(
            0, "ZIP Extraction",
            ex.Message, "", 0);

        Dts.TaskResult = (int)ScriptResults.Failure;
    }
}


